	else
	begin
		cycle<=cycle+1;
		if(stall_w && (!m_axi_wvalid || m_axi_wdata!==saved_wdata || m_axi_wlast!==saved_wlast)) $fatal(1,"W changed while stalled");
		if(stall_ar && (!m_axi_arvalid || m_axi_araddr!==saved_araddr)) $fatal(1,"AR changed while stalled");
		if(stall_aw && (!m_axi_awvalid || m_axi_awaddr!==saved_awaddr)) $fatal(1,"AW changed while stalled");
		stall_w<=m_axi_wvalid && !m_axi_wready;
		stall_ar<=m_axi_arvalid && !m_axi_arready;
		stall_aw<=m_axi_awvalid && !m_axi_awready;
		saved_wdata<=m_axi_wdata; saved_wlast<=m_axi_wlast;
		saved_araddr<=m_axi_araddr; saved_awaddr<=m_axi_awaddr;
		if(m_axi_arvalid && m_axi_arready)
		begin
			if(write_active || m_axi_bvalid) $fatal(1,"More than one outstanding transaction");
			if(m_axi_arburst!=1 || m_axi_arsize!=2 || m_axi_arid!=0 || m_axi_araddr[1:0]!=0) $fatal(1,"Bad AR attributes");
			if(int'(m_axi_araddr[11:0])+(int'(m_axi_arlen)+1)*4>4096) $fatal(1,"AR crosses 4KB");
			ra<=int'(m_axi_araddr>>2); rb<=int'(m_axi_arlen)+1; read_active<=1; reads<=reads+1;
		end
		if(m_axi_rvalid && m_axi_rready)
		begin
			m_axi_rvalid<=0;
			ra<=ra+1; rb<=rb-1;
			if(rb==1) read_active<=0;
		end
		if(read_active && !m_axi_rvalid && cycle%4!=0)
		begin
			m_axi_rdata<=mem[ra]; m_axi_rlast<=(rb==1);
			m_axi_rresp<=inject_read ? 2'b10 : 2'b00; m_axi_rvalid<=1;
		end
		if(m_axi_awvalid && m_axi_awready)
		begin
			if(read_active || m_axi_rvalid) $fatal(1,"Read and write overlap");
			if(m_axi_awburst!=1 || m_axi_awsize!=2 || m_axi_awid!=0 || m_axi_awaddr[1:0]!=0) $fatal(1,"Bad AW attributes");
			if(int'(m_axi_awaddr[11:0])+(int'(m_axi_awlen)+1)*4>4096) $fatal(1,"AW crosses 4KB");
			wa<=int'(m_axi_awaddr>>2); wb<=int'(m_axi_awlen)+1; write_active<=1; writes<=writes+1;
		end
		if(m_axi_wvalid && m_axi_wready)
		begin
			if(m_axi_wlast!=(wb==1) || m_axi_wstrb!=15) $fatal(1,"Bad WLAST/WSTRB");
			mem[wa]<=m_axi_wdata; wa<=wa+1; wb<=wb-1;
			if(wb==1)
			begin write_active<=0; m_axi_bvalid<=1; m_axi_bresp<=inject_write ? 2'b10 : 2'b00; end
		end
		if(m_axi_bvalid && m_axi_bready) m_axi_bvalid<=0;
	end
end
task automatic cpu_write(input logic [31:0] addr,data,input logic [3:0] strb,input logic [1:0] resp);
	begin
		// Alternate AW-first and W-first to exercise independent Lite channels.
		if(cases%2==0)
		begin
			@(negedge aclk); s_axi_awaddr=addr; s_axi_awvalid=1;
			do @(posedge aclk); while(!s_axi_awready);
			@(negedge aclk); s_axi_awvalid=0;
			repeat(2) @(negedge aclk);
			s_axi_wdata=data; s_axi_wstrb=strb; s_axi_wvalid=1;
			do @(posedge aclk); while(!s_axi_wready);
			@(negedge aclk); s_axi_wvalid=0;
		end
		else
		begin
			@(negedge aclk); s_axi_wdata=data; s_axi_wstrb=strb; s_axi_wvalid=1;
			do @(posedge aclk); while(!s_axi_wready);
			@(negedge aclk); s_axi_wvalid=0;
			repeat(2) @(negedge aclk);
			s_axi_awaddr=addr; s_axi_awvalid=1;
			do @(posedge aclk); while(!s_axi_awready);
			@(negedge aclk); s_axi_awvalid=0;
		end
		wait(s_axi_bvalid);
		repeat(2) @(negedge aclk);
		if(!s_axi_bvalid || s_axi_bresp!==resp) $fatal(1,"Lite write response addr=%h",addr);
		s_axi_bready=1;
		@(negedge aclk); s_axi_bready=0;
	end
endtask
task automatic cpu_read(input logic [31:0] addr,output logic [31:0] data,input logic [1:0] resp);
	logic [31:0] held;
	begin
		@(negedge aclk); s_axi_araddr=addr; s_axi_arvalid=1;
		do @(posedge aclk); while(!s_axi_arready);
		@(negedge aclk); s_axi_arvalid=0;
		wait(s_axi_rvalid); held=s_axi_rdata;
		repeat(2) @(negedge aclk);
		if(!s_axi_rvalid || s_axi_rdata!==held || s_axi_rresp!==resp) $fatal(1,"Lite read response");
		data=s_axi_rdata; s_axi_rready=1;
		@(negedge aclk); s_axi_rready=0;
	end
endtask
task automatic run_job(input integer count,input bit expect_error,input bit test_busy);
	integer polls;
	begin
		cpu_write(12,3,15,0);
		cpu_write(8,3,15,0);
		cpu_write(0,1,15,0);
		if(test_busy)
		begin
			cpu_write(0,1,15,2);
			cpu_write(16,5,15,2);
		end
		polls=0;
		do
		begin cpu_read(4,value,0); polls=polls+1; if(polls>20000) $fatal(1,"Job timeout"); end
		while(value[2:1]==0 || value[0]);
		if(value[2:1] !== (expect_error ? 2'b10 : 2'b01)) $fatal(1,"Unexpected job status %h",value);
		if(!irq_o) $fatal(1,"Missing IRQ");
		if(!expect_error)
			for(int i=0;i<count;i=i+1)
				if(mem[(32'hcffc>>2)+i]!==expected[i]) $fatal(1,"Case %0d result %0d got %h expected %h",cases,i,mem[(32'hcffc>>2)+i],expected[i]);
		cpu_write(12,3,15,0);
		if(irq_o) $fatal(1,"IRQ clear failed");
		cases=cases+1;
	end
endtask
